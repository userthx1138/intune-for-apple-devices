# Apple Business Manager Email

The process to register for Apple Business Manager is straight forward.

There is a guide here _https://www.apple.com/business/site/docs/Apple_Business_Manager_Getting_Started_Guide.pdf_ and online documentation here https://support.apple.com/en-au/guide/apple-business-manager/axm402206497/web

 
Essentially you just go to _https://business.apple.com_ and select Enrol now. 
 
You will need to know you DUNS which you can look up at _https://express.illion.com.au/_

 
The result I got for your organisation was:

![Apple Business Manager Email](images/Apple%20Business%20Manager%20Email.png)

 
When you sign up you will need to provide an email address that’s associated with your business. Consumer email addresses from services such as Gmail or Yahoo Mail won’t be accepted. The email can not already be used as an Apple ID. The account associated with this email address becomes the initial administrator for Apple Business Manager. This will also be the address that Apple uses should there ever be a need for support so consider using an email address that can be accessed by other staff at your organisation.

There will be a verification process so you will need to nominate someone in your organisation who can accept the terms of ABM on behalf of the company.

Once you have completed the signup you will need to ask your supplier for a Reseller ID and supply them with your Organisation ID from within Apple Business Manager so that future device purchases will be automatically populated.
 
